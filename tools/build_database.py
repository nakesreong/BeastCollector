def translate_color_label(label: str) -> str:
    if not label:
        return "Стандартный окрас"
    s = label.strip()
    s = s.replace(" w/ ", " с ").replace(" & ", " и ")
    for en, ru in sorted(COLOR_WORDS_RU.items(), key=lambda kv: -len(kv[0])):
        s = re.sub(r"\b" + re.escape(en) + r"\b", ru, s)
    return s


def lua_escape(s: str) -> str:
    if s is None:
        return ""
    return s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n").replace("\r", "")


def ensure_cache_files(force_fetch: bool = False):
    os.makedirs(CACHE_DIR, exist_ok=True)
    for fname, url in UPSTREAM_SOURCES.items():
        fpath = os.path.join(CACHE_DIR, fname)
        if force_fetch or not os.path.exists(fpath) or os.path.getsize(fpath) == 0:
            print(f"[fetch] Downloading {fname} from {url} ...")
            req = urllib.request.Request(url, headers={"User-Agent": "Mozilla/5.0 (BeastCollector Builder)"})
            with urllib.request.urlopen(req, timeout=90) as resp, open(fpath, "wb") as out:
                data = resp.read()
                out.write(data)
            print(f"        Saved {len(data):,} bytes -> {fpath}")


