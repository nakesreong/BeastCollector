def load_creature_db():
    creature_ru_name = {}
    creature_disp = {}
    with open(os.path.join(CACHE_DIR, "Creature_ruRU.csv"), encoding="utf-8") as f:
        for r in csv.DictReader(f):
            cid = int(r["ID"])
            if r["Name_lang"]:
                creature_ru_name[cid] = r["Name_lang"].strip()
            d0 = int(r["DisplayID_0"]) if r["DisplayID_0"] else 0
            d1 = int(r["DisplayID_1"]) if r["DisplayID_1"] else 0
            if d0 > 0 and d1 == 0:
                creature_disp[cid] = d0

    with open(os.path.join(CACHE_DIR, "CreatureDisplayDB_retail_db_general.lua"), encoding="utf-8") as f:
        for line in f:
            if line.startswith("t[") and "=[=[" in line:
                m = re.match(r"t\[\d+\]=\[=\[([^\t]+)\t(.*)\]=\]", line.strip())
                if m:
                    for zchunk in m.group(2).split(";"):
                        parts = zchunk.split(":")
                        if len(parts) == 3 and parts[1] and parts[2]:
                            nids = [int(x) for x in parts[1].split(",") if x]
                            dids = [int(x) for x in parts[2].split(",") if x]
                            if len(dids) == 1:
                                for n in nids:
                                    if n not in creature_disp:
                                        creature_disp[n] = dids[0]

    return creature_ru_name, creature_disp


def load_ghp_coords():
    ghp_by_npc = {}
    with open(os.path.join(CACHE_DIR, "GHP_Data.lua"), encoding="utf-8") as f:
        ghp_text = f.read()

    entry_pattern = re.compile(
        r'\["zone_name"\]\s*=\s*"([^"]+)",\s*'
        r'\["zoneID"\]\s*=\s*(\d+),\s*'
        r'\["name"\]\s*=\s*"([^"]+)",.*?'
        r'\["class"\]\s*=\s*"([^"]+)",.*?'
        r'\["NpcId"\]\s*=\s*(\d+),\s*'
        r'\["coords"\]\s*=\s*\{(.*?)\}\s*,\s*\}',
        re.S,
    )
    for m in entry_pattern.finditer(ghp_text):
        zname, zid_s, name, cls, npcid_s, coords_s = m.groups()
        npcid = int(npcid_s)
        zid = int(zid_s)
        pts = re.findall(r"\{\s*([0-9.]+)\s*,\s*([0-9.]+)\s*\}", coords_s)
        # Pick up to 4 well-spaced coordinates
        all_pts = [(float(x), float(y)) for x, y in pts]
        selected_pts = []
        for pt in all_pts:
            if len(selected_pts) >= 4:
                break
            if all(abs(pt[0] - sp[0]) + abs(pt[1] - sp[1]) >= 3.5 for sp in selected_pts):
                selected_pts.append(pt)
        if not selected_pts and all_pts:
            selected_pts = [all_pts[0]]

        if npcid not in ghp_by_npc or len(selected_pts) > len(ghp_by_npc[npcid]["coords"]):
            ghp_by_npc[npcid] = {
                "zoneID": zid,
                "zone_name": zname,
                "name": name,
                "class": cls,
                "coords": selected_pts,
            }
    return ghp_by_npc


def parse_petopia_gallery(uimap_ru, resolve_zone, creature_ru_name, creature_disp, ghp_by_npc):
    with open(os.path.join(CACHE_DIR, "petopia_gallery.html"), encoding="utf-8") as f:
        html = f.read()

    tooltips = dict(re.findall(r'tooltips\.(tt\w+)\s*=\s*"(.*?)";', html))

    token_re = re.compile(
        r"<h2 class='gallery familyname' id='family=([^']+)'>([^<]+)</h2>|"
        r"<h3 class='gallery modelname' id='model=([^']+)'>([^<]+)</h3>|"
        r"<div class='gallery_looks_thumb'><a href='/look\.php\?id=([^']+)'(?:\s+id='(tt[^']+)')?[^>]*>"
        r"<img[^>]*alt='([^']*)'[^>]*><span class='look_thumb_label_section'>"
        r"<span class='look_thumb_label'><span class='look_thumb_name'>([^<]*)</span>"
    )

    raw_looks = []
    npc_look_count = defaultdict(int)
    cur_fam = None
    cur_model = None

    row_re = re.compile(
        r"<tr><td class='name'>.*?<a href='/npc\.php\?id=(\d+)'>([^<]+)</a></div>"
        r"(?:<div class='pettabletitle'>([^<]*)</div>)?</td>"
        r"<td class='level'>(.*?)</td>"
        r"<td class='zone'>(.*?)</td></tr>"
    )

    for m in token_re.finditer(html):
        if m.group(1):
            cur_fam = (m.group(1), html_lib.unescape(m.group(2).strip()))
        elif m.group(3):
            cur_model = (m.group(3), html_lib.unescape(m.group(4).strip()))
        else:
            look_id = m.group(5).strip()
            tt_id = m.group(6)
            alt_name = html_lib.unescape(m.group(7).strip())
            var_label = html_lib.unescape(m.group(8).strip())
            if not tt_id or tt_id not in tooltips:
                continue

            tt_html = tooltips[tt_id]
            npc_rows = []
            seen_nids = set()
            for rm in row_re.finditer(tt_html):
                nid = int(rm.group(1))
                if nid in seen_nids:
                    continue
                seen_nids.add(nid)
                nname = html_lib.unescape(rm.group(2).strip())
                lvl_raw = rm.group(4)
                z_raw = html_lib.unescape(rm.group(5).strip())
                lvl_clean = re.sub(r"<[^>]+>", " ", lvl_raw).strip()
                lvl_num = lvl_clean.split()[0] if lvl_clean else "?"

                is_boss = "Boss" in lvl_raw
                is_rare = "Rare" in lvl_raw
                is_spawned = "Spawned" in lvl_raw
                is_elite = "Elite" in lvl_raw

                tag = ""
                if is_boss:
                    tag = "Босс"
                elif is_rare and is_elite:
                    tag = "Редкая элита"
                elif is_rare:
                    tag = "Рарник"
                elif is_spawned:
                    tag = "Особый призыв"
                elif is_elite:
                    tag = "Элита"

                npc_rows.append({
                    "id": nid,
                    "name_en": nname,
                    "name_ru": creature_ru_name.get(nid),
                    "level": lvl_num,
                    "tag": tag,
                    "is_boss": is_boss,
                    "is_rare": is_rare,
                    "is_spawned": is_spawned,
                    "is_elite": is_elite,
                    "zone_en": z_raw,
                })
                npc_look_count[nid] += 1

            if not npc_rows:
                continue

            raw_looks.append({
                "fam_slug": cur_fam[0],
                "fam_en": cur_fam[1],
                "model_slug": cur_model[0] if cur_model else "",
                "model_en": cur_model[1] if cur_model else "",
                "look_id": look_id,
                "alt_name": alt_name,
                "var_label": var_label,
                "npc_rows": npc_rows,
            })

    # Build final Beast entries
    beasts = []
    for item in raw_looks:
        fam_slug = item["fam_slug"]
        fam_meta = FAMILY_META.get(fam_slug)
        if not fam_meta:
            continue

        npc_rows = item["npc_rows"]

        # Choose the best primary NPC for 3D rendering and waypoint navigation:
        # 1. Curated NPC if present
        # 2. Single-look NPC (npc_look_count[id] == 1) so SetCreature(npcID) is 100% deterministic
        # 3. Has GHP coordinates
        # 4. Has static DB2 displayID
        # 5. Rare / Named
        def score_npc(row):
            nid = row["id"]
            is_curated = 1 if nid in CURATED_BY_NPC else 0
            is_single_look = 1 if npc_look_count[nid] == 1 else 0
            has_ghp = 1 if nid in ghp_by_npc else 0
            has_disp = 1 if nid in creature_disp else 0
            is_special = 1 if (row["is_rare"] or row["is_boss"] or row["is_spawned"]) else 0
            return (is_curated, is_single_look, has_ghp, has_disp, is_special, -npc_look_count[nid])

        best_npc = max(npc_rows, key=score_npc)
        primary_nid = best_npc["id"]
        curated = CURATED_BY_NPC.get(primary_nid)

        # Verified 1-to-1 DisplayID only
        verified_disp = creature_disp.get(primary_nid) if npc_look_count[primary_nid] == 1 else None

        # Determine rarity badge
        if curated and "rarity" in curated:
            rarity = curated["rarity"]
        elif fam_slug == "spiritbeast":
            rarity = "SPIRIT"
        elif any(r["is_boss"] for r in npc_rows):
            rarity = "BOSS"
        elif any(r["is_spawned"] for r in npc_rows) and len(npc_rows) <= 2:
            rarity = "SECRET"
        elif any(r["is_rare"] for r in npc_rows):
            rarity = "RARE"
        else:
            rarity = "COMMON"

        # Resolve zone & mapID & coordinates
        ghp_info = ghp_by_npc.get(primary_nid)
        if not ghp_info:
            for r in npc_rows:
                if r["id"] in ghp_by_npc:
                    ghp_info = ghp_by_npc[r["id"]]
                    break

        map_id = None
        zone_ru = None
        coords = []

        if curated and "mapID" in curated:
            map_id = curated["mapID"]
            zone_ru = uimap_ru.get(map_id, best_npc["zone_en"])
            coords = list(curated.get("coords", []))
        elif ghp_info:
            map_id = ghp_info["zoneID"]
            zone_ru = uimap_ru.get(map_id)
            if not zone_ru:
                _, zone_ru = resolve_zone(ghp_info["zone_name"])
            coords = [(x, y, ghp_info["name"]) for x, y in ghp_info["coords"]]
        else:
            map_id, zone_ru = resolve_zone(best_npc["zone_en"])

        if not zone_ru:
            _, zone_ru = resolve_zone(best_npc["zone_en"])

        # Determine Title & Subtitle
        color_ru = translate_color_label(item["var_label"] or item["alt_name"])
        primary_name_display = best_npc["name_ru"] or best_npc["name_en"]

        if curated:
            b_name = curated["name"]
            b_sub = curated["subTitle"]
        elif len(npc_rows) == 1 or best_npc["is_rare"] or best_npc["is_boss"]:
            b_name = primary_name_display
            b_sub = f"{item['model_en']} ({color_ru})"
        else:
            b_name = f"{primary_name_display} ({color_ru})"
            b_sub = f"{item['model_en']} — {item['alt_name']}"

        # Build compact top NPCs list (up to 6) for the Side Inspector Dock
        top_npcs = []
        for r in npc_rows[:6]:
            _, r_zone_ru = resolve_zone(r["zone_en"])
            r_name = f"{r['name_ru']} ({r['name_en']})" if r["name_ru"] else r["name_en"]
            top_npcs.append({
                "id": r["id"],
                "name": r_name,
                "level": r["level"],
                "tag": r["tag"],
                "zone": r_zone_ru,
            })

        all_nids = [r["id"] for r in npc_rows]

        beasts.append({
            "id": f"{fam_slug}_{item['look_id']}",
            "lookID": item["look_id"],
            "family": fam_slug,
            "modelGroup": item["model_en"],
            "name": b_name,
            "subTitle": b_sub,
            "npcID": primary_nid,
            "displayID": verified_disp,
            "npcIDs": all_nids,
            "npcs": top_npcs,
            "rarity": rarity,
            "zone": zone_ru,
            "mapID": map_id,
            "coords": coords,
            "respawn": curated.get("respawn") if curated else None,
            "howTo": curated.get("howTo") if curated else None,
        })

    # Sort beasts within each family so curated / Spirit / Boss / Rare come first, then by model group
    rarity_rank = {"SPIRIT": 0, "SECRET": 1, "BOSS": 2, "RARE": 3, "COMMON": 4}
    fam_rank = {slug: idx for idx, slug in enumerate(FAMILY_ORDER)}
    beasts.sort(key=lambda b: (
        fam_rank.get(b["family"], 999),
        0 if b["npcID"] in CURATED_BY_NPC else 1,
        rarity_rank.get(b["rarity"], 5),
        b["modelGroup"],
        b["id"],
    ))
    return beasts


