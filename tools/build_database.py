def translate_color_label(label: str) -> str:
    if not label:
        return "Стандартный окрас"
    s = label.strip()
    s = s.replace(" w/ ", " с ").replace(" & ", " и ")
    for en, ru in sorted(COLOR_WORDS_RU.items(), key=lambda kv: -len(kv[0])):
        s = re.sub(r"\b" + re.escape(en) + r"\b", ru, s)
    return s


def lua_escape(s: str) -> str:
    if s is None:
        return ""
    return s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n").replace("\r", "")


